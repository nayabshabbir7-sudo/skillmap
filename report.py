"""PDF progress report for SkillMap (needs the reportlab package)."""

from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    Flowable,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

NAVY = colors.HexColor("#0B1D4D")
CYAN = colors.HexColor("#0891B2")
VIOLET = colors.HexColor("#6D28D9")
AMBER = colors.HexColor("#B45309")
INK = colors.HexColor("#1E293B")
MUTED = colors.HexColor("#64748B")
LINE = colors.HexColor("#CBD5E1")
SOFT = colors.HexColor("#F1F5F9")


def _safe(text):
    """The built-in PDF fonts only support Latin-1, so replace other characters."""
    text = str(text or "")
    text = text.encode("latin-1", "replace").decode("latin-1")
    return escape(text)


class ProgressBar(Flowable):
    def __init__(self, fraction, width, height=10):
        super().__init__()
        self.fraction = max(0.0, min(1.0, fraction))
        self.width = width
        self.height = height

    def wrap(self, avail_width, avail_height):
        return self.width, self.height

    def draw(self):
        self.canv.setFillColor(LINE)
        self.canv.roundRect(0, 0, self.width, self.height, self.height / 2, stroke=0, fill=1)
        if self.fraction > 0:
            self.canv.setFillColor(CYAN)
            self.canv.roundRect(
                0, 0, max(self.height, self.width * self.fraction), self.height,
                self.height / 2, stroke=0, fill=1,
            )


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MUTED)
    canvas.drawString(18 * mm, 10 * mm, "Generated by SkillMap - Career Tracker")
    canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def _table(rows, col_widths, header=True):
    table = Table(rows, colWidths=col_widths, repeatRows=1 if header else 0)
    style = [
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (-1, -1), INK),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE),
    ]
    if header:
        style += [
            ("BACKGROUND", (0, 0), (-1, 0), NAVY),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ]
    table.setStyle(TableStyle(style))
    return table


def build_pdf_report(data):
    """Create the report and return it as PDF bytes.

    `data` keys: name, username, role, generated, readiness (0-1), level,
    breakdown [(label, done, total)], skills [(name, learned)],
    tasks [(title, done, proof_url)], study {total_minutes, week_minutes, streak}.
    """
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=18 * mm,
        title="SkillMap Career Progress Report",
        author="SkillMap",
    )
    width = A4[0] - 36 * mm

    base = getSampleStyleSheet()
    h_title = ParagraphStyle("t", parent=base["Title"], fontName="Helvetica-Bold",
                             fontSize=22, textColor=colors.white, alignment=0, leading=26)
    h_sub = ParagraphStyle("s", parent=base["Normal"], fontName="Helvetica",
                           fontSize=10, textColor=colors.HexColor("#CBD5E1"))
    h2 = ParagraphStyle("h2", parent=base["Heading2"], fontName="Helvetica-Bold",
                        fontSize=13, textColor=NAVY, spaceBefore=14, spaceAfter=6)
    body = ParagraphStyle("b", parent=base["Normal"], fontName="Helvetica",
                          fontSize=10, textColor=INK, leading=14)
    small = ParagraphStyle("sm", parent=body, fontSize=8, textColor=MUTED)
    cell = ParagraphStyle("c", parent=body, fontSize=9, leading=12)
    big = ParagraphStyle("big", parent=body, leading=34)

    story = []

    header = Table(
        [
            [Paragraph("Career Progress Report", h_title)],
            [Paragraph(
                f"{_safe(data['name'])} (@{_safe(data['username'])}) &nbsp;|&nbsp; "
                f"{_safe(data['role'])} &nbsp;|&nbsp; {_safe(data['generated'])}",
                h_sub,
            )],
        ],
        colWidths=[width],
    )
    header.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), NAVY),
        ("LEFTPADDING", (0, 0), (-1, -1), 14),
        ("RIGHTPADDING", (0, 0), (-1, -1), 14),
        ("TOPPADDING", (0, 0), (0, 0), 16),
        ("BOTTOMPADDING", (0, -1), (-1, -1), 14),
    ]))
    story += [header, Spacer(1, 10)]

    pct = int(round(data["readiness"] * 100))
    story.append(Paragraph("Career Readiness", h2))
    story.append(Paragraph(
        f"<font size=26 color='#0891B2'><b>{pct}%</b></font> &nbsp; "
        f"<font color='#64748B'>{_safe(data['level'])}</font>",
        big,
    ))
    bar = ProgressBar(data["readiness"], width - 2, 12)
    bar.hAlign = "LEFT"
    story += [Spacer(1, 4), bar, Spacer(1, 10)]

    rows = [["Area", "Completed", "Total", "Progress"]]
    for label, done, total in data["breakdown"]:
        percent = f"{(done / total):.0%}" if total else "-"
        rows.append([_safe(label), str(done), str(total), percent])
    story.append(_table(rows, [width * 0.46, width * 0.18, width * 0.16, width * 0.20]))

    story.append(Paragraph("Skills", h2))
    rows = [["Skill", "Status"]]
    for name, learned in data["skills"]:
        status = (
            "<font color='#0E7490'><b>Learned</b></font>" if learned
            else "<font color='#B45309'>Need Practice</font>"
        )
        rows.append([Paragraph(_safe(name), cell), Paragraph(status, cell)])
    story.append(_table(rows, [width * 0.65, width * 0.35]))

    if data["tasks"]:
        story.append(Paragraph("Practical Tasks", h2))
        rows = [["Task", "Status", "Proof of work"]]
        for title, done, proof in data["tasks"]:
            status = (
                "<font color='#0E7490'><b>Completed</b></font>" if done
                else "<font color='#B45309'>Pending</font>"
            )
            rows.append([
                Paragraph(_safe(title), cell),
                Paragraph(status, cell),
                Paragraph(_safe(proof) if proof else "-", cell),
            ])
        story.append(_table(rows, [width * 0.32, width * 0.2, width * 0.48]))

    study = data["study"]
    story.append(Paragraph("Study Activity", h2))
    rows = [
        ["Current streak", f"{study['streak']} day(s)"],
        ["This week", f"{study['week_minutes'] / 60:.1f} hours"],
        ["Total study time", f"{study['total_minutes'] / 60:.1f} hours"],
    ]
    story.append(_table(rows, [width * 0.5, width * 0.5], header=False))

    story += [
        Spacer(1, 14),
        Paragraph(
            "This report was generated automatically from the learner's own SkillMap "
            "progress data. Readiness = skills (50%), practical tasks (30%) and "
            "interview practice (20%).",
            small,
        ),
    ]

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()